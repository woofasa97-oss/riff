const WEEKDAYS: Weekday[] = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun']

/**
 * Compact availability spec: 'm' morning, 'a' afternoon, 'e' evening.
 * `availability('--e', '--e', '', 'ae', '-ae', 'ma-', '')` reads left-to-right Mon→Sun.
 */
function availability(note: string, ...days: string[]): Availability {
  const grid = {} as Record<Weekday, Slot[]>
  WEEKDAYS.forEach((day, i) => {
    const spec = days[i] ?? ''
    const slots: Slot[] = []
    if (spec.includes('m')) slots.push('morning')
    if (spec.includes('a')) slots.push('afternoon')
    if (spec.includes('e')) slots.push('evening')
    grid[day] = slots
  })
  return { grid, note }
}

/**
 * Deterministic peaks for the inline waveform. Real peak extraction is out of scope for v1
 * (docs/SPEC.md §6 stubs the audio players), but the shape has to be stable across renders
 * or the server and client markup diverge.
 */
function waveform(seed: number, bars = 32): number[] {
  const peaks: number[] = []
  let x = seed
  for (let i = 0; i < bars; i++) {
    x = (x * 1103515245 + 12345) % 2147483648
    peaks.push(0.25 + (x / 2147483648) * 0.75)
  }
  return peaks
}

function clip(id: string, durationSec: number, seed: number, recordedAt: string): AudioClip {
  return { id, url: `/mock/clips/${id}.m4a`, durationSec, waveform: waveform(seed), recordedAt }
}

